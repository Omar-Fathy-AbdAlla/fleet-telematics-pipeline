WITH snapshot_rows AS (
    SELECT DISTINCT
        DRIVER_ID,
        SNAPSHOT_DATE,
        FIRST_NAME,
        LAST_NAME,
        CDL_CLASS,
        LICENSE_STATE,
        LICENSE_NUMBER,
        HOME_TERMINAL,
        YEARS_EXPERIENCE,
        HIRE_DATE,
        DATE_OF_BIRTH,
        TERMINATION_DATE,
        EMPLOYMENT_STATUS
    FROM {{ ref('drivers') }}
    WHERE DRIVER_ID IS NOT NULL
      AND SNAPSHOT_DATE IS NOT NULL
),

with_previous_values AS (
    SELECT *,
        LAG(SNAPSHOT_DATE) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_SNAPSHOT_DATE,
        LAG(FIRST_NAME) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_FIRST_NAME,
        LAG(LAST_NAME) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_LAST_NAME,
        LAG(CDL_CLASS) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_CDL_CLASS,
        LAG(LICENSE_STATE) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_LICENSE_STATE,
        LAG(LICENSE_NUMBER) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_LICENSE_NUMBER,
        LAG(HOME_TERMINAL) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_HOME_TERMINAL,
        LAG(YEARS_EXPERIENCE) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_YEARS_EXPERIENCE,
        LAG(HIRE_DATE) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_HIRE_DATE,
        LAG(DATE_OF_BIRTH) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_DATE_OF_BIRTH,
        LAG(TERMINATION_DATE) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_TERMINATION_DATE,
        LAG(EMPLOYMENT_STATUS) OVER (
            PARTITION BY DRIVER_ID ORDER BY SNAPSHOT_DATE
        ) AS PREV_EMPLOYMENT_STATUS
    FROM snapshot_rows
),

change_flags AS (
    SELECT *,
        CASE
            WHEN PREV_SNAPSHOT_DATE IS NULL THEN TRUE
            WHEN FIRST_NAME IS DISTINCT FROM PREV_FIRST_NAME
              OR LAST_NAME IS DISTINCT FROM PREV_LAST_NAME
              OR CDL_CLASS IS DISTINCT FROM PREV_CDL_CLASS
              OR LICENSE_STATE IS DISTINCT FROM PREV_LICENSE_STATE
              OR LICENSE_NUMBER IS DISTINCT FROM PREV_LICENSE_NUMBER
              OR HOME_TERMINAL IS DISTINCT FROM PREV_HOME_TERMINAL
              OR YEARS_EXPERIENCE IS DISTINCT FROM PREV_YEARS_EXPERIENCE
              OR HIRE_DATE IS DISTINCT FROM PREV_HIRE_DATE
              OR DATE_OF_BIRTH IS DISTINCT FROM PREV_DATE_OF_BIRTH
              OR TERMINATION_DATE IS DISTINCT FROM PREV_TERMINATION_DATE
              OR EMPLOYMENT_STATUS IS DISTINCT FROM PREV_EMPLOYMENT_STATUS
            THEN TRUE
            ELSE FALSE
        END AS HAS_CHANGED
    FROM with_previous_values
),

version_starts AS (
    SELECT
        DRIVER_ID,
        SNAPSHOT_DATE AS VALID_FROM,
        FIRST_NAME,
        LAST_NAME,
        CDL_CLASS,
        LICENSE_STATE,
        HOME_TERMINAL,
        YEARS_EXPERIENCE,
        HIRE_DATE,
        TERMINATION_DATE,
        EMPLOYMENT_STATUS
    FROM change_flags
    WHERE HAS_CHANGED = TRUE
),

version_periods AS (
    SELECT *,
        LEAD(VALID_FROM) OVER (
            PARTITION BY DRIVER_ID ORDER BY VALID_FROM
        ) AS NEXT_VALID_FROM
    FROM version_starts
),

final AS (
    SELECT
        ROW_NUMBER() OVER (
            ORDER BY V.DRIVER_ID, V.VALID_FROM
        )::INTEGER AS DRIVER_KEY,
        V.DRIVER_ID,
        V.FIRST_NAME,
        V.LAST_NAME,
        V.FIRST_NAME || ' ' || V.LAST_NAME AS FULL_NAME,
        V.HIRE_DATE,
        V.LICENSE_STATE,
        V.CDL_CLASS,
        V.YEARS_EXPERIENCE,
        L.LOCATION_KEY AS HOME_TERMINAL_LOCATION_KEY,
        V.EMPLOYMENT_STATUS,
        V.TERMINATION_DATE,
        V.VALID_FROM,
        COALESCE(
            DATEADD(DAY, -1, V.NEXT_VALID_FROM)::DATE,
            TO_DATE('9999-12-31')
        ) AS VALID_TO,
        V.NEXT_VALID_FROM IS NULL AS IS_CURRENT
    FROM version_periods V
    LEFT JOIN {{ ref('dim_location') }} L
        ON UPPER(TRIM(V.HOME_TERMINAL)) = UPPER(TRIM(L.CITY))
)

SELECT * FROM final