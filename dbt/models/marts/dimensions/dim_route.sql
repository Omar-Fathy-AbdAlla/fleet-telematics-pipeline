{{ config(materialized='table') }}

WITH unique_routes AS (
    SELECT
        ROUTE_ID,
        ORIGIN_CITY,
        ORIGIN_STATE,
        DESTINATION_CITY,
        DESTINATION_STATE,
        BASE_RATE_PER_KM,
        FUEL_SURCHARGE_RATE_PER_KM,
        TYPICAL_TRANSIT_DAYS,
        TYPICAL_DISTANCE_KM
    FROM {{ ref('routes') }}
    WHERE ROUTE_ID IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ROUTE_ID
        ORDER BY ROUTE_ID
    ) = 1
),

final AS (
    SELECT
        ROW_NUMBER() OVER (
            ORDER BY R.ROUTE_ID
        )::INTEGER AS ROUTE_KEY,

        R.ROUTE_ID,

        R.ORIGIN_CITY || ' → ' || R.DESTINATION_CITY
            AS LANE_NAME,

        L_ORIGIN.LOCATION_KEY AS ORIGIN_LOCATION_KEY,
        L_DESTINATION.LOCATION_KEY AS DESTINATION_LOCATION_KEY,

        R.TYPICAL_DISTANCE_KM,
        R.TYPICAL_TRANSIT_DAYS,

        R.BASE_RATE_PER_KM AS BASE_RATE_PER_KM_USD,
        R.FUEL_SURCHARGE_RATE_PER_KM
            AS FUEL_SURCHARGE_RATE_PER_KM_USD

    FROM unique_routes R

    LEFT JOIN {{ ref('dim_location') }} L_ORIGIN
        ON UPPER(TRIM(R.ORIGIN_CITY)) = UPPER(TRIM(L_ORIGIN.CITY))
       AND UPPER(TRIM(R.ORIGIN_STATE)) = UPPER(TRIM(L_ORIGIN.STATE_CODE))

    LEFT JOIN {{ ref('dim_location') }} L_DESTINATION
        ON UPPER(TRIM(R.DESTINATION_CITY)) = UPPER(TRIM(L_DESTINATION.CITY))
       AND UPPER(TRIM(R.DESTINATION_STATE)) = UPPER(TRIM(L_DESTINATION.STATE_CODE))
)

SELECT * FROM final