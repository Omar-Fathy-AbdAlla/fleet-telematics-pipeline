WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'trucks') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(TRUCK_ID), '') AS TRUCK_ID,
        NULLIF(TRIM(VIN), '') AS VIN,
        INITCAP(NULLIF(TRIM(MAKE), '')) AS MAKE,
        INITCAP(NULLIF(TRIM(STATUS), '')) AS STATUS,
        INITCAP(NULLIF(TRIM(FUEL_TYPE), '')) AS FUEL_TYPE,
        TRY_TO_NUMBER(NULLIF(TRIM(MODEL_YEAR), '')) AS MODEL_YEAR,
        NULLIF(TRIM(UNIT_NUMBER), '') AS UNIT_NUMBER,
        INITCAP(NULLIF(TRIM(HOME_TERMINAL), '')) AS HOME_TERMINAL,
        TRY_TO_DATE(NULLIF(TRIM(SNAPSHOT_DATE), '')) AS SNAPSHOT_DATE,
        TRY_TO_DATE(NULLIF(TRIM(ACQUISITION_DATE), '')) AS ACQUISITION_DATE,
        ROUND(
        TRY_TO_NUMBER(NULLIF(TRIM(TANK_CAPACITY_GALLONS), '')) * 3.78541, 
            2
        ) AS TANK_CAPACITY_LITERS,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(ACQUISITION_MILEAGE), ''), 18, 2) * 1.609344, 
            2
        ) AS ACQUISITION_MILEAGE_KM
    FROM source_data
)
SELECT * FROM cleaned