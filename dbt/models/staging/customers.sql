WITH source_data AS (

    SELECT *
    FROM {{ source('raw_data', 'customers') }}

),

cleaned AS (

    SELECT
        NULLIF(TRIM(CUSTOMER_ID), '') AS CUSTOMER_ID,
        INITCAP(NULLIF(TRIM(CUSTOMER_NAME), '')) AS CUSTOMER_NAME,
        INITCAP(NULLIF(TRIM(CUSTOMER_TYPE), '')) AS CUSTOMER_TYPE,
        INITCAP(NULLIF(TRIM(ACCOUNT_STATUS), '')) AS ACCOUNT_STATUS,
        TRY_TO_NUMBER(NULLIF(TRIM(CREDIT_TERMS_DAYS), '')) AS CREDIT_TERMS_DAYS,
        TRY_TO_DATE(NULLIF(TRIM(CONTRACT_START_DATE), '')) AS CONTRACT_START_DATE,
        INITCAP(NULLIF(TRIM(PRIMARY_FREIGHT_TYPE), '')) AS PRIMARY_FREIGHT_TYPE,
        TRY_TO_NUMBER(NULLIF(TRIM(ANNUAL_REVENUE_POTENTIAL), '')) AS ANNUAL_REVENUE_POTENTIAL

    FROM source_data

)

SELECT *
FROM cleaned
