WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'delivery_events') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(LOAD_ID), '') AS LOAD_ID,
        NULLIF(TRIM(TRIP_ID), '') AS TRIP_ID,
        NULLIF(TRIM(EVENT_ID), '') AS EVENT_ID,
        UPPER(NULLIF(TRIM(EVENT_TYPE), '')) AS EVENT_TYPE,
        NULLIF(TRIM(FACILITY_ID), '') AS FACILITY_ID,
        UPPER(NULLIF(TRIM(ON_TIME_FLAG), '')) AS ON_TIME_FLAG,
        INITCAP(NULLIF(TRIM(LOCATION_CITY), '')) AS LOCATION_CITY,
        UPPER(NULLIF(TRIM(LOCATION_STATE), '')) AS LOCATION_STATE,
        TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ACTUAL_DATETIME), '')) AS ACTUAL_DATETIME,
        TRY_TO_NUMBER(NULLIF(TRIM(DETENTION_MINUTES), '')) AS DETENTION_MINUTES,
        TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(SCHEDULED_DATETIME), '')) AS SCHEDULED_DATETIME
    FROM source_data
)
SELECT * FROM cleaned