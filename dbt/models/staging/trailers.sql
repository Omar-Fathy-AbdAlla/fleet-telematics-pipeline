WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'trailers') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(TRAILER_ID), '') AS TRAILER_ID,
        NULLIF(TRIM(VIN), '') AS VIN,
        NULLIF(TRIM(TRAILER_NUMBER), '') AS TRAILER_NUMBER,
        INITCAP(NULLIF(TRIM(TRAILER_TYPE), '')) AS TRAILER_TYPE,
        INITCAP(NULLIF(TRIM(STATUS), '')) AS STATUS,
        TRY_TO_NUMBER(NULLIF(TRIM(MODEL_YEAR), '')) AS MODEL_YEAR,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(LENGTH_FEET), ''), 18, 2) * 0.3048, 
            2
        ) AS LENGTH_METERS,
        INITCAP(NULLIF(TRIM(CURRENT_LOCATION), '')) AS CURRENT_LOCATION,
        TRY_TO_DATE(NULLIF(TRIM(ACQUISITION_DATE), '')) AS ACQUISITION_DATE,
        TRY_TO_DATE(NULLIF(TRIM(SNAPSHOT_DATE), '')) AS SNAPSHOT_DATE
    FROM source_data
)
SELECT * FROM cleaned