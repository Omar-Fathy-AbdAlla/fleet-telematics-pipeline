WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'maintenance_records') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(MAINTENANCE_ID), '') AS MAINTENANCE_ID,
        NULLIF(TRIM(TRUCK_ID), '') AS TRUCK_ID,
        TRY_TO_DATE(NULLIF(TRIM(MAINTENANCE_DATE), '')) AS MAINTENANCE_DATE,
        INITCAP(NULLIF(TRIM(MAINTENANCE_TYPE), '')) AS MAINTENANCE_TYPE,
        TRY_TO_NUMBER(NULLIF(TRIM(LABOR_COST), ''), 18, 2) AS LABOR_COST,
        TRY_TO_NUMBER(NULLIF(TRIM(PARTS_COST), ''), 18, 2) AS PARTS_COST,
        TRY_TO_NUMBER(NULLIF(TRIM(TOTAL_COST), ''), 18, 2) AS TOTAL_COST,
        TRY_TO_NUMBER(NULLIF(TRIM(LABOR_HOURS), ''), 18, 2) AS LABOR_HOURS,
        TRY_TO_NUMBER(NULLIF(TRIM(DOWNTIME_HOURS), ''), 18, 2) AS DOWNTIME_HOURS,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(ODOMETER_READING), ''), 18, 2) * 1.609344, 
            2
        ) AS ODOMETER_READING_KM,
        INITCAP(NULLIF(TRIM(FACILITY_LOCATION), '')) AS FACILITY_LOCATION,
        NULLIF(TRIM(SERVICE_DESCRIPTION), '') AS SERVICE_DESCRIPTION
    FROM source_data
)
SELECT * FROM cleaned