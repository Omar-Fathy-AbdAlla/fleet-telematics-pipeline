WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'drivers') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(DRIVER_ID), '') AS DRIVER_ID,
        INITCAP(NULLIF(TRIM(FIRST_NAME), '')) AS FIRST_NAME,
        INITCAP(NULLIF(TRIM(LAST_NAME), '')) AS LAST_NAME,
        UPPER(NULLIF(TRIM(CDL_CLASS), '')) AS CDL_CLASS,
        INITCAP(NULLIF(TRIM(HOME_TERMINAL), '')) AS HOME_TERMINAL,
        UPPER(NULLIF(TRIM(LICENSE_STATE), '')) AS LICENSE_STATE,
        NULLIF(TRIM(LICENSE_NUMBER), '') AS LICENSE_NUMBER,
        TRY_TO_NUMBER(NULLIF(TRIM(YEARS_EXPERIENCE), '')) AS YEARS_EXPERIENCE,
        TRY_TO_DATE(NULLIF(TRIM(HIRE_DATE), '')) AS HIRE_DATE,
        TRY_TO_DATE(NULLIF(TRIM(DATE_OF_BIRTH), '')) AS DATE_OF_BIRTH,
        DATEDIFF(
            year, 
            TRY_TO_DATE(NULLIF(TRIM(DATE_OF_BIRTH), '')), 
            CURRENT_DATE()
        ) AS AGE,
        TRY_TO_DATE(NULLIF(TRIM(TERMINATION_DATE), '')) AS TERMINATION_DATE,
        TRY_TO_DATE(NULLIF(TRIM(SNAPSHOT_DATE), '')) AS SNAPSHOT_DATE,
        INITCAP(NULLIF(TRIM(EMPLOYMENT_STATUS), '')) AS EMPLOYMENT_STATUS
    FROM source_data
)
SELECT * FROM cleaned