WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'routes') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(ROUTE_ID), '') AS ROUTE_ID,
        INITCAP(NULLIF(TRIM(ORIGIN_CITY), '')) AS ORIGIN_CITY,
        UPPER(NULLIF(TRIM(ORIGIN_STATE), '')) AS ORIGIN_STATE,
        INITCAP(NULLIF(TRIM(DESTINATION_CITY), '')) AS DESTINATION_CITY,
        UPPER(NULLIF(TRIM(DESTINATION_STATE), '')) AS DESTINATION_STATE,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(BASE_RATE_PER_MILE), ''), 18, 4) / 1.609344, 
            4
        ) AS BASE_RATE_PER_KM,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(FUEL_SURCHARGE_RATE), ''), 18, 4) / 1.609344, 
            4
        ) AS FUEL_SURCHARGE_RATE_PER_KM,
        TRY_TO_NUMBER(NULLIF(TRIM(TYPICAL_TRANSIT_DAYS), ''), 18, 0) AS TYPICAL_TRANSIT_DAYS,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(TYPICAL_DISTANCE_MILES), ''), 18, 2) * 1.609344, 
            2
        ) AS TYPICAL_DISTANCE_KM

    FROM source_data
)
SELECT * FROM cleaned