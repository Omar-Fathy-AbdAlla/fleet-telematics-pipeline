WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'trips') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(TRIP_ID), '') AS TRIP_ID,
        NULLIF(TRIM(LOAD_ID), '') AS LOAD_ID,
        NULLIF(TRIM(TRUCK_ID), '') AS TRUCK_ID,
        NULLIF(TRIM(DRIVER_ID), '') AS DRIVER_ID,
        NULLIF(TRIM(TRAILER_ID), '') AS TRAILER_ID,
        TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(DISPATCH_TS), '')) AS DISPATCH_TS,
        TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(ARRIVAL_TS), '')) AS ARRIVAL_TS,
        TRY_TO_DATE(NULLIF(TRIM(DISPATCH_DATE), '')) AS DISPATCH_DATE,
        INITCAP(NULLIF(TRIM(TRIP_STATUS), '')) AS TRIP_STATUS,
        CASE 
            WHEN TRY_TO_NUMBER(NULLIF(TRIM(AVERAGE_MPG), ''), 18, 3) = 0 THEN 0
            ELSE ROUND(235.214583 / TRY_TO_NUMBER(NULLIF(TRIM(AVERAGE_MPG), ''), 18, 3), 2)
        END AS AVERAGE_L_PER_100KM,
        TRY_TO_NUMBER(NULLIF(TRIM(IDLE_TIME_HOURS), ''), 18, 2) AS IDLE_TIME_HOURS,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(FUEL_GALLONS_USED), ''), 18, 3) * 3.78541, 
            3
        ) AS FUEL_LITERS_USED,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(ACTUAL_DISTANCE_MILES), ''), 18, 2) * 1.609344, 
            2
        ) AS ACTUAL_DISTANCE_KM,
        TRY_TO_NUMBER(NULLIF(TRIM(ACTUAL_DURATION_HOURS), ''), 18, 2) AS ACTUAL_DURATION_HOURS

    FROM source_data
)
SELECT * FROM cleaned