WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'safety_incidents') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(INCIDENT_ID), '') AS INCIDENT_ID,
        NULLIF(TRIM(TRIP_ID), '') AS TRIP_ID,
        NULLIF(TRIM(TRUCK_ID), '') AS TRUCK_ID,
        NULLIF(TRIM(DRIVER_ID), '') AS DRIVER_ID,
        TRY_TO_DATE(NULLIF(TRIM(INCIDENT_DATE), '')) AS INCIDENT_DATE,
        INITCAP(NULLIF(TRIM(INCIDENT_TYPE), '')) AS INCIDENT_TYPE,
        NULLIF(TRIM(DESCRIPTION), '') AS DESCRIPTION,
        UPPER(NULLIF(TRIM(INJURY_FLAG), '')) AS INJURY_FLAG,
        UPPER(NULLIF(TRIM(AT_FAULT_FLAG), '')) AS AT_FAULT_FLAG,
        UPPER(NULLIF(TRIM(PREVENTABLE_FLAG), '')) AS PREVENTABLE_FLAG,
        TRY_TO_NUMBER(NULLIF(TRIM(CLAIM_AMOUNT), ''), 18, 2) AS CLAIM_AMOUNT,
        TRY_TO_NUMBER(NULLIF(TRIM(CARGO_DAMAGE_COST), ''), 18, 2) AS CARGO_DAMAGE_COST,
        TRY_TO_NUMBER(NULLIF(TRIM(VEHICLE_DAMAGE_COST), ''), 18, 2) AS VEHICLE_DAMAGE_COST,
        INITCAP(NULLIF(TRIM(LOCATION_CITY), '')) AS LOCATION_CITY,
        UPPER(NULLIF(TRIM(LOCATION_STATE), '')) AS LOCATION_STATE
    FROM source_data
)
SELECT * FROM cleaned