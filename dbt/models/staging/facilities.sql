WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'facilities') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(FACILITY_ID), '') AS FACILITY_ID,
        INITCAP(NULLIF(TRIM(FACILITY_NAME), '')) AS FACILITY_NAME,
        INITCAP(NULLIF(TRIM(FACILITY_TYPE), '')) AS FACILITY_TYPE,
        INITCAP(NULLIF(TRIM(CITY), '')) AS CITY,
        UPPER(NULLIF(TRIM(STATE), '')) AS STATE,
        TRY_TO_NUMBER(NULLIF(TRIM(LATITUDE), ''), 12, 7) AS LATITUDE,
        TRY_TO_NUMBER(NULLIF(TRIM(LONGITUDE), ''), 12, 7) AS LONGITUDE,
        TRY_TO_NUMBER(NULLIF(TRIM(DOCK_DOORS), '')) AS DOCK_DOORS,
        NULLIF(TRIM(OPERATING_HOURS), '') AS OPERATING_HOURS
    FROM source_data
)
SELECT * FROM cleaned