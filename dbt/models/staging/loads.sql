WITH source_data AS (
    SELECT * FROM {{ source('raw_data', 'loads') }}
),
cleaned AS (
    SELECT
        NULLIF(TRIM(LOAD_ID), '') AS LOAD_ID,
        NULLIF(TRIM(CUSTOMER_ID), '') AS CUSTOMER_ID,
        NULLIF(TRIM(ROUTE_ID), '') AS ROUTE_ID,
        INITCAP(NULLIF(TRIM(LOAD_TYPE), '')) AS LOAD_TYPE,
        TRY_TO_NUMBER(NULLIF(TRIM(PIECES), '')) AS PIECES,
        INITCAP(NULLIF(TRIM(BOOKING_TYPE), '')) AS BOOKING_TYPE,
        ROUND(
            TRY_TO_NUMBER(NULLIF(TRIM(WEIGHT_LBS), ''), 18, 2) * 0.45359237, 
            2
        ) AS WEIGHT_KG,
        TRY_TO_NUMBER(NULLIF(TRIM(FUEL_SURCHARGE), ''), 18, 2) AS FUEL_SURCHARGE,
        TRY_TO_NUMBER(NULLIF(TRIM(REVENUE), ''), 18, 2) AS REVENUE,
        TRY_TO_NUMBER(NULLIF(TRIM(ACCESSORIAL_CHARGES), ''), 18, 2) AS ACCESSORIAL_CHARGES,
        INITCAP(NULLIF(TRIM(LOAD_STATUS), '')) AS LOAD_STATUS,
        TRY_TO_DATE(NULLIF(TRIM(LOAD_DATE), '')) AS LOAD_DATE
    FROM source_data
)
SELECT * FROM cleaned